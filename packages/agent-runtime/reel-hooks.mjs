export const REEL_HOOK_CLASSIFY_ORDER = Object.freeze([
  1, 23, 5, 4, 3, 15, 20, 7, 9, 26, 25, 24, 18, 17, 8, 6, 16, 12, 10, 2, 13, 19, 21, 22, 11, 14,
]);

const formulaById = new Map(REEL_HOOK_FORMULAS.map((f) => [f.id, f]));

/**
 * Classifies a spoken hook line into one of the 26 playbook formulas (EN or AR).
 */
export function classifyReelHook(text) {
  if (typeof text !== "string" || !text.trim()) return null;
  const trimmed = text.trim();
  for (const id of REEL_HOOK_CLASSIFY_ORDER) {
    const formula = formulaById.get(id);
    if (!formula) continue;
    try {
      if (new RegExp(formula.match, "iu").test(trimmed) || new RegExp(formula.ar.match, "iu").test(trimmed)) {
        return { id: formula.id, name: formula.name, name_ar: formula.ar.name };
      }
    } catch {
      // Ignore malformed pattern safely.
    }
  }
  return null;
}

/**
 * Compact 26-formula catalog formatted for Gemini system instructions without
 * blowing context budgets. Uses Gulf phrasing when dialect is gulf/sa.
 */
export function compactHookCatalogForPrompt({ language = "en", dialect = "msa", bilingual = false } = {}) {
  const gulfFlavored = dialect === "gulf" || dialect === "sa";
  const lines = [];
  if (language === "ar" && !bilingual) {
    lines.push("26 Hook Formulas Playbook (Arabic — adapt naturally to dialect, keep plural-polite register, max 6 words on-screen):");
    for (const f of REEL_HOOK_FORMULAS) {
      const ex = gulfFlavored ? f.ar.example_gulf : f.ar.example;
      lines.push(`#${f.id} ${f.ar.name} (${f.name}): ${f.ar.template} | Ex: ${ex} | Screen: ${f.ar.on_screen} | Trap: ${f.ar.trap}`);
    }
    return lines.join("\n");
  }
  if (bilingual) {
    lines.push("26 Hook Formulas Playbook (English + Arabic templates; write native hooks in both languages, max 6 words on-screen):");
    for (const f of REEL_HOOK_FORMULAS) {
      const arEx = gulfFlavored ? f.ar.example_gulf : f.ar.example;
      lines.push(`#${f.id} ${f.name} / ${f.ar.name}: EN "${f.template}" (Screen: ${f.on_screen}) | AR "${f.ar.template}" (Ex: ${arEx}; Screen: ${f.ar.on_screen}) | Trap: ${f.trap}`);
    }
    return lines.join("\n");
  }
  lines.push("26 Hook Formulas Playbook (pick 3 DISTINCT formula IDs; max 6 words on-screen):");
  for (const f of REEL_HOOK_FORMULAS) {
    lines.push(`#${f.id} ${f.name}: ${f.template} | Ex: ${f.example} | Screen: ${f.on_screen} | Trap: ${f.trap}`);
  }
  return lines.join("\n");
}
