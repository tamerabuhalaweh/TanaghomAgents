// Creative Studio bilingual strings. Single dictionary for EN + AR so both
// locales stay complete by construction (pinned by unit test). Arabic copy
// uses Modern Standard Arabic, RTL-safe punctuation, and Eastern-Arabic-free
// numerals where counts must stay machine-readable.

export type CreativeLocale = "en" | "ar";

export const CREATIVE_LOCALE_COOKIE = "tanaghom_locale";

export function normalizeLocale(value: unknown): CreativeLocale {
  return value === "ar" ? "ar" : "en";
}

export function directionOf(locale: CreativeLocale): "rtl" | "ltr" {
  return locale === "ar" ? "rtl" : "ltr";
}

